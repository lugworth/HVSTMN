def glyph(drawing):
    rows = drawing.split()
    if len(rows) != 9 or any(len(row) != 7 or set(row) - {".", "#"} for row in rows):
        raise ValueError("Expected a 7 by 9 drawing of dots and hashes")
    pen = TTGlyphPen(None)
    left_edge = (ADVANCE - 7 * PIXEL_W) // 2
    for row, pixels in enumerate(rows):
        bottom = (8 - row) * PIXEL_H
        for run in finditer(r"#+", pixels):
            left = left_edge + run.start() * PIXEL_W
            right = left_edge + run.end() * PIXEL_W
            pen.moveTo((left, bottom))
            pen.lineTo((left, bottom + PIXEL_H))
            pen.lineTo((right, bottom + PIXEL_H))
            pen.lineTo((right, bottom))
            pen.closePath()
    return pen.glyph()


def main():
    if len(ART) > 0x100:
        raise ValueError("Farm symbols must fit in the U+E900–E9FF font range")
    codepoints = {0xE900 + i: name for i, name in enumerate(ART)}
    fb = FontBuilder(EM, isTTF=True)
    glyphs = {".notdef": TTGlyphPen(None).glyph()}
    glyphs.update({name: glyph(drawing) for name, (_, drawing) in ART.items()})
    fb.setupGlyphOrder(list(glyphs))
    fb.setupCharacterMap(codepoints)
    fb.setupGlyf(glyphs)
    # Match the monospaced canvas grid to the DejaVu font metrics.
    fb.setupHorizontalMetrics({name: (ADVANCE, getattr(outline, "xMin", 0)) for name, outline in glyphs.items()})
    fb.setupHorizontalHeader(ascent=1901, descent=-483)
    fb.setupNameTable({
        "familyName": FAMILY,
        "styleName": "Regular",
        "uniqueFontIdentifier": f"{FAMILY} 1.0",
        "fullName": FAMILY,
        "psName": "FurrowFarmSymbols-Regular",
        "version": "Version 1.000",
    })
    fb.setupOS2(sTypoAscender=1556, sTypoDescender=-492, sTypoLineGap=410,
                usWinAscent=1901, usWinDescent=483, fsType=0)
    fb.setupPost(isFixedPitch=1)
    fb.setupMaxp()
    font = fb.font
    font.recalcTimestamp = False
    font["head"].created = font["head"].modified = 2082844800  # 1970-01-01
    font.flavor = "woff"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    font.save(OUT)

    names = ",\n".join(f"  {name}: '\\u{cp:04X}'" for cp, name in codepoints.items())
    fallbacks = ",\n".join(f"  [FARM_SYMBOLS.{name}]: {fallback!r}" for name, (fallback, _) in ART.items())
    TS_OUT.write_text("// Generated by scripts/build-farm-font.py.\n"
                      f"export const FARM_SYMBOLS = {{\n{names},\n}} as const;\n\n"
                      f"export const FARM_SYMBOL_FALLBACK: Readonly<Partial<Record<string, string>>> = {{\n{fallbacks},\n}};\n",
                      encoding="utf-8")

    print(f"Built {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")
    print(f"Built {TS_OUT.relative_to(ROOT)} with {len(ART)} glyphs at {ADVANCE} units per cell")


if __name__ == "__main__":
    main()
